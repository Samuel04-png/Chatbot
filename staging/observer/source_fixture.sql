);
CREATE TABLE public.messages (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, phone text NOT NULL,
 role text NOT NULL CHECK(role IN ('user','bot')), message text NOT NULL, message_en text,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX messages_phone_id_idx ON public.messages(phone,id);
CREATE TABLE public.referrals (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, phone text NOT NULL, source text NOT NULL,
 user_id text, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.orders (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, phone text NOT NULL, user_id text,
 product text NOT NULL, price text, quantity integer NOT NULL, address text,
 status text NOT NULL DEFAULT 'pending', created_at timestamptz NOT NULL DEFAULT now()
);
